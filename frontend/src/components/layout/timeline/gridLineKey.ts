/**
 * 显式网格线数组的“内容键”工具（供 BackgroundGrid 的重绘跳过判定使用）。
 *
 * BackgroundGrid 为性能采用了“绘制参数未变化就跳过重建 SVG path”的优化：
 * 只有当内容键变化时才重算 path。该键必须对**所有**网格线位置完整敏感 ——
 * 任何一条线移动都必须使键变化，否则会产生“网格滞后于数据”的错位假象。
 *
 * ★ 回归防御（历史 bug）：
 * 早期实现用 `长度 + 前 3 条 + 后 3 条` 抽样做校验和。拖动 Tempo Map 的
 * **中间**变化点时（水平缩放较小），受影响的是以该点为锚、位于数组**中部**
 * 的整段网格线：它们随标签整体平移，但总条数与首尾几条线往往都不变
 * （首尾线属于视口边缘、锚点未受拖动的其它段），抽样校验和因此误判
 * “无需重绘”。结果是网格线只在拖到“有线进出视口 / 条数变化”时才跳变
 * 刷新一次（视觉上网格与标签错位），松手后依旧错位，直到水平滚动或
 * 缩放触发重绘才恢复。轨道视图与参数编辑器共用本组件，故两处都受影响。
 * 这里必须是完整序列键，不能抽样。
 */

/** 完整内容键：null / 空数组 / 长度 + 全部位置（浮点精确序列化）。 */
export function explicitGridLinesKey(xs: number[] | null | undefined): string {
    if (!xs) return "-";
    if (xs.length === 0) return "0";
    return `${xs.length}|${xs.join(",")}`;
}
