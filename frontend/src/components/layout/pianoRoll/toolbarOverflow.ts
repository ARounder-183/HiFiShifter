/**
 * 参数编辑器工具栏「水平不足 ⇒ 分级隐藏」的判据（纯逻辑，便于单测）。
 *
 * # 为什么需要
 * 工具栏横向不足时，若放任浏览器自行压缩，中文标签会被压到**逐字折行**
 * （`参数编辑器` 变成两行「参数编 / 辑器」）—— 这是最丑的一种降级。正确做法是
 * 按优先级**离散地隐藏**冗余项，直到放得下。
 *
 * # 判据为什么是对称的
 * 隐藏到"刚好放得下"为止，恢复也到"刚好放得下"为止：同一宽度下，
 * 压缩过程与恢复过程得到**同一套**排版。若改用"滞后余量"（进入用阈值 A、
 * 退出用 A - H），恢复会比压缩晚一截，用户能观察到两条路径排版不一致。
 *
 * 现在不需要任何"滞后余量"或逐帧逼近：层级由**一次完整测量**直接算出
 * （见 `toolbarGauge.chooseTier`）。同一宽度下压缩与恢复得到同一结果，
 * 因为判据是同一个纯函数，而不是两条方向相反的规则。
 *
 * # 层级约定
 * `0` = 全部显示；数值越大隐藏越多，具体对应见 `panel/ParamToolbar.tsx` 里的 `ToolbarSlot` 使用点。
 */

/** 第 10 级：静态枚举参数与算法下拉收进「⋯」菜单。 */
export const TIER_STATIC_PARAMS = 10;

/** 第 11 级：参数药丸整排（参考轨道组 / 子音高组 / 参数药丸）收进「⋯」菜单。 */
export const TIER_ALL_PILLS = 11;

/**
 * 最大隐藏层级。
 *
 * 1 标题 · 2 算法文本 · 3 张力药丸 · 4 气声药丸（开关保留）· 5 平滑度文本 ·
 * 6 平滑度数值 · 7 平滑度滑块 · 8 导入 MIDI · 9 参考轨道组文本 ·
 * **10 静态参数 + 算法下拉 → 「⋯」** · **11 参数药丸整排 → 「⋯」**。
 *
 * 顺序说明：**数值在滑块之前**让位 —— 滑块是控件、数值只是读数，读数先走才合理。
 * 两个被门禁的药丸**逐个**让位，且**先张力后气声**：气声药丸左侧挂着分离开关，
 * 先让气声会让开关独自悬空。
 *
 * # 为什么第 10/11 级是「收进菜单」而不是「隐藏」
 *
 * 1-9 级砍的都是**冗余**（重复的标题文字、可以缩小的滑块）。再往下剩下的每一项都是
 * **唯一入口** —— 隐藏它们等于让某个功能在窄面板里彻底消失。因此 10/11 级把它们
 * 搬进「⋯」菜单：宽度不再占用，功能一个不少。
 *
 * # 为什么到 11 级为止（没有第 12 级）
 *
 * 第 11 级之后右簇只剩「⋯」这一个按钮（约 28px），左簇最小 216px，合计约 260px ——
 * 再往下已经没有可让的东西。原计划里的"第 12 级：整个右簇进菜单"与第 11 级宽度相同，
 * 加了也只是同一件事的第二个名字，因此不设。
 */
export const TOOLBAR_MAX_TIER = TIER_ALL_PILLS;
