std::vector<PianoRollComponent::CvvcBoundaryHandle> PianoRollComponent::cvvcBoundaryHandles() const
{
    std::vector<CvvcBoundaryHandle> result;
    if(sourceEditMode || (tool!=Tool::note && tool!=Tool::amplitude && tool!=Tool::flagCurve))return result;
    for(const auto& hit:noteHits)if(usesCvvcEnvelope(hit.id))
    {
        const auto& spans=diffSingerPhonemes.at(hit.id.toStdString());
        for(size_t i=1;i<spans.size();++i)
        {
            const auto& left=spans[i-1];const auto& right=spans[i];
            if((right.envelopePart!=2&&right.envelopePart!=3)||left.envelopePart<=0
                ||std::abs(left.endSeconds-right.startSeconds)>1.e-6)continue;
            const auto x=timeToX(hit.startSeconds+hit.clipStartSeconds+right.startSeconds);
            result.push_back({hit.id,right.envelopePart,{x-4.f,hit.bounds.getY()+3.f,8.f,std::max(2.f,hit.bounds.getHeight()-6.f)}});
        }
    }
    return result;
}

std::optional<PianoRollComponent::CvvcBoundaryHandle> PianoRollComponent::cvvcBoundaryAt(juce::Point<float> at) const
{
    const auto handles=cvvcBoundaryHandles();
    for(auto it=handles.rbegin();it!=handles.rend();++it)if(it->bounds.contains(at))return *it;
    return {};
}

juce::Rectangle<float> PianoRollComponent::diagnosticCvvcBoundary(const juce::String& id,int part) const
{
    for(const auto& handle:cvvcBoundaryHandles())if(handle.noteId==id&&handle.part==part)return handle.bounds;
    return {};
}

bool PianoRollComponent::cvvcBoundaryMouseDown(const juce::MouseEvent& event)
{
    if(!event.mods.isLeftButtonDown()||event.mods.isPopupMenu())return false;
    const auto handle=cvvcBoundaryAt(event.position);if(!handle)return false;
    const auto* note=findNote(handle->noteId);if(!note||note->durationSeconds<=0)return false;
    const auto& spans=diffSingerPhonemes.at(handle->noteId.toStdString());
    for(size_t i=1;i<spans.size();++i)if(spans[i].envelopePart==handle->part)
    {
        cvvcBoundaryDrag=CvvcBoundaryDrag{note->id,handle->part,note->durationSeconds,
            spans[i].startSeconds,spans[i].startSeconds,spans[i-1].startSeconds,spans[i].endSeconds,
            model.revisionNumber(),spans};
        pendingCvvcBoundary.reset();cvvcLaneDrag.reset();draggedNote.clear();dragMode=DragMode::none;
        selectedNote=note->id;selectedNotes={note->id.toStdString()};
        cvvcSelectedNote=note->id;cvvcSelectedPart=handle->part;
        grabKeyboardFocus();setMouseCursor(juce::MouseCursor::LeftRightResizeCursor);
        if(onNoteSelected)onNoteSelected(selectedNote);
        repaint();return true;
    }
    return false;
}

void PianoRollComponent::applyCvvcBoundaryPreview()
{
    auto* preview=cvvcBoundaryDrag?&*cvvcBoundaryDrag:pendingCvvcBoundary?&*pendingCvvcBoundary:nullptr;
    if(!preview)return;
    if(preview->revision!=model.revisionNumber())
    {cvvcBoundaryDrag.reset();pendingCvvcBoundary.reset();return;}
    const auto key=preview->noteId.toStdString();
    // A fresh canonical layout supersedes the bridge after mouse-up.
    if(!cvvcBoundaryDrag && diffSingerPhonemes.contains(key)){pendingCvvcBoundary.reset();return;}
    auto spans=preview->spans;
    for(size_t i=1;i<spans.size();++i)if(spans[i].envelopePart==preview->part)
    {
        spans[i-1].endSeconds=preview->position;
        spans[i].startSeconds=preview->position;
        // Actual crossfade windows are regenerated by the renderer. Do not
        // stretch old sample windows into a supposedly authoritative preview.
        for(auto& p:spans)p.mixEnvelope={};
        break;
    }
    diffSingerPhonemes[key]=std::move(spans);
}

void PianoRollComponent::cvvcBoundaryMouseDrag(const juce::MouseEvent& event)
{
    if(!cvvcBoundaryDrag)return;
    if(cvvcBoundaryDrag->revision!=model.revisionNumber())
    {cvvcBoundaryDrag.reset();refreshFromModel();return;}
    auto& draft=*cvvcBoundaryDrag;
    draft.position=backend::clampCvvcBoundary(draft.original
        +(event.position.x-event.mouseDownPosition.x)/pixelsPerSecond,draft.from,draft.to);
    applyCvvcBoundaryPreview();repaint();
}

void PianoRollComponent::finishCvvcBoundaryDrag()
{
    if(!cvvcBoundaryDrag)return;
    auto draft=std::move(*cvvcBoundaryDrag);cvvcBoundaryDrag.reset();
    if(std::abs(draft.position-draft.original)>1.e-8
        &&model.setCvvcBoundary(draft.noteId,draft.part,draft.position/draft.duration,draft.revision))
    {draft.revision=model.revisionNumber();pendingCvvcBoundary=std::move(draft);}
    refreshFromModel();repaint();
}

bool PianoRollComponent::hasSelectedCvvcPhoneme() const
{
    if (sourceEditMode || selectedNotes.size()!=1 || !selectedNotes.contains(cvvcSelectedNote.toStdString())
        || !usesCvvcEnvelope(cvvcSelectedNote)) return false;
    const auto& spans=diffSingerPhonemes.at(cvvcSelectedNote.toStdString());
    return std::any_of(spans.begin(),spans.end(),[&](const auto& p){return p.envelopePart==cvvcSelectedPart;});
}

std::optional<PianoRollComponent::CvvcEnvelopeSelection> PianoRollComponent::selectedCvvcEnvelope() const
{
    if(hasSelectedCvvcPhoneme())for(const auto& piece:cvvcLanePieces(true))
        if(piece.noteId==cvvcSelectedNote&&piece.part==cvvcSelectedPart)
            return CvvcEnvelopeSelection{piece.noteId,piece.token,piece.part,piece.from,piece.to,piece.points};
    return {};
}

std::vector<PianoRollComponent::CvvcPhonemeTab> PianoRollComponent::cvvcPhonemeTabs() const
{
    std::vector<CvvcPhonemeTab> tabs;
    if (sourceEditMode) return tabs;
    for (const auto& hit:noteHits)
    {
        if (!usesCvvcEnvelope(hit.id)) continue;
        for (const auto& span:diffSingerPhonemes.at(hit.id.toStdString()))
        {
            if (span.envelopePart<=0) continue;
            const auto left=timeToX(hit.startSeconds+hit.clipStartSeconds+span.startSeconds);
            const auto right=timeToX(hit.startSeconds+hit.clipStartSeconds+span.endSeconds);
            // Use nominal phoneme boundaries, not overlapping OTO lead-ins,
            // so adjacent tabs have distinct click targets.
            if (right-left<4.f) continue;
            const juce::Rectangle<float> bounds(left+1.f,hit.bounds.getY()-16.f,
                std::min(110.f,right-left-2.f),14.f);
            tabs.push_back({hit.id,span.token,span.envelopePart,bounds});
        }
    }
    return tabs;
}

juce::Rectangle<float> PianoRollComponent::diagnosticCvvcPhonemeTab(const juce::String& id,int part) const
{
    for (const auto& tab:cvvcPhonemeTabs()) if(tab.noteId==id&&tab.part==part)return tab.bounds;
    return {};
}

void PianoRollComponent::drawCvvcPhonemeTabs(juce::Graphics& g) const
{
    const auto focused=hasSelectedCvvcPhoneme();
    const auto clip=g.getClipBounds().toFloat();
    std::unordered_map<std::string,juce::Rectangle<float>> boundsByNote;
    for(const auto& hit:noteHits)boundsByNote.emplace(hit.id.toStdString(),hit.bounds);
    if(showEnvelope || tool==Tool::amplitude)for(const auto& piece:cvvcLanePieces(true))
        if(const auto hit=boundsByNote.find(piece.noteId.toStdString());hit!=boundsByNote.end())
        {
            const auto bounds=hit->second;
            const auto* note=findNote(piece.noteId);if(!note)continue;
            const auto selected=focused&&piece.noteId==cvvcSelectedNote&&piece.part==cvvcSelectedPart;
            auto end=piece.to;
            if(piece.mixEnvelope.available())
            {
                end=piece.mixEnvelope.endSeconds();
                for(const auto& ramp:piece.mixEnvelope.ramps)if(!ramp.rising&&ramp.activeSamples<0)
                    end=std::min(end,piece.mixEnvelope.startSeconds+(ramp.start+ramp.length)/piece.mixEnvelope.sampleRate);
            }
            const auto left=timeToX(piece.from),right=timeToX(end);
            if(right<clip.getX()||left>clip.getRight()||bounds.getBottom()<clip.getY()
                ||bounds.getY()-bounds.getHeight()>clip.getBottom())continue;
            const auto steps=juce::jlimit(2,1600,static_cast<int>(right-left));
            juce::Path path;
            for(int i=0;i<=steps;++i)
            {
                const auto t=piece.from+(end-piece.from)*i/steps;
                auto gain=backend::envelopeGainFromDb(piece.mixEnvelope.replacesStandardEnvelope
                    &&backend::isStandardCvvcEnvelope(piece.points,piece.to-piece.from)?0.f
                    :backend::cvvcEnvelopeValue(piece.points,(t-piece.from)/(piece.to-piece.from),true));
                if(piece.mixEnvelope.available())gain*=piece.mixEnvelope.gainAt(t);
                const auto y=bounds.getBottom()-gain*note->amplitudeEnvelopeBasePercent/100.f*bounds.getHeight();
                const auto x=left+(right-left)*i/steps;
                if(i==0)path.startNewSubPath(x,y);else path.lineTo(x,y);
            }
            const auto ink=rollRole(juce::Colour(piece.part==1?0xff70d9d0:piece.part==3?0xffc1a0f4:0xffffb65e),
                piece.part==1?Palette::noteEdge:piece.part==3?Palette::text:Palette::textMuted);
            g.setColour(rollInk(ink.withAlpha(selected?1.f:.6f),Palette::noteFill));
            g.strokePath(path,juce::PathStrokeType(selected?2.f:1.f));
        }
    for(const auto& handle:cvvcBoundaryHandles())
    {
        const auto colour=rollRole(juce::Colour(handle.part==3?0xffc1a0f4:0xffffb65e),
            handle.part==3?Palette::text:Palette::noteEdge);
        const auto x=handle.bounds.getCentreX();
        g.setColour(rollInk(colour.withAlpha(.85f),Palette::noteFill));
        g.drawVerticalLine(static_cast<int>(std::round(x)),handle.bounds.getY()-3.f,handle.bounds.getBottom()+3.f);
        g.fillRoundedRectangle(x-2.f,handle.bounds.getCentreY()-3.f,4.f,6.f,1.f);
    }
    g.setFont(10.f);
    for (const auto& tab:cvvcPhonemeTabs())
    {
        if(!clip.intersects(tab.bounds.expanded(0,20)))continue;
        const auto selected=focused&&tab.noteId==cvvcSelectedNote&&tab.part==cvvcSelectedPart;
        const auto colour=rollRole(juce::Colour(tab.part==1?0xff70d9d0:tab.part==3?0xffc1a0f4:0xffffb65e),
            tab.part==1?Palette::noteEdge:tab.part==3?Palette::text:Palette::textMuted);
        const auto surface=selected?rollRole(colour,Palette::selection):Palette::panelRaised;
        g.setColour(surface);g.fillRoundedRectangle(tab.bounds,3.f);
        g.setColour(rollInk(selected?rollRole(Palette::background,Palette::heading):colour,surface));
        g.drawRoundedRectangle(tab.bounds,3.f,1.f);
        g.setColour(rollText(selected?Palette::background:colour,surface));
        g.drawText(tab.token,tab.bounds.reduced(3.f,0),juce::Justification::centredLeft,true);
        if(selected)for(const auto& hit:noteHits)if(hit.id==tab.noteId)
        {
            const auto& spans=diffSingerPhonemes.at(hit.id.toStdString());
            for(const auto& p:spans)if(p.envelopePart==tab.part)
            {
                const auto x=timeToX(hit.startSeconds+hit.clipStartSeconds+p.startSeconds);
                const auto end=timeToX(hit.startSeconds+hit.clipStartSeconds+p.endSeconds);
                g.setColour(colour);g.drawRoundedRectangle({x,hit.bounds.getY(),std::max(1.f,end-x),hit.bounds.getHeight()},2.f,2.f);
            }
        }
    }
}

bool PianoRollComponent::cvvcPhonemeTabMouseDown(const juce::MouseEvent& event)
{
    if(sourceEditMode || event.mods.isPopupMenu()
        || (tool==Tool::amplitude&&amplitudeLaneBounds().contains(event.position))
        || (tool==Tool::flagCurve&&flagLaneBounds().contains(event.position))) return false;
    const auto tabs=cvvcPhonemeTabs();
    for(auto it=tabs.rbegin();it!=tabs.rend();++it)if(it->bounds.contains(event.position))
    {
        cvvcLaneDrag.reset();draggedNote.clear();dragMode=DragMode::none;
        selectedNote=it->noteId;selectedNotes={it->noteId.toStdString()};
        cvvcSelectedNote=it->noteId;cvvcSelectedPart=it->part;
        grabKeyboardFocus();
        if(onNoteSelected)onNoteSelected(selectedNote);
        repaint();return true;
    }
    return false;
}

int PianoRollComponent::crossfadeSelectedNotes(bool curved)
{
    if (selectedNotes.size() != 2) return 0;
    refreshFromModel();
    const auto revision = model.revisionNumber();
    std::vector<ProjectModel::CrossfadeSpan> spans;
    for (const auto& piece : cvvcLanePieces(true))
        if (selectedNotes.contains(piece.noteId.toStdString()))
        {
            ProjectModel::CrossfadeSpan span {piece.noteId,piece.part,piece.from,piece.to,{}};
            for (const auto& p : piece.points) span.points.push_back({piece.from+p.position*(piece.to-piece.from),p.value,p.linear});
            if (piece.mixEnvelope.available())
            {
                span.soundingEnd = piece.mixEnvelope.endSeconds();
                for (const auto& ramp : piece.mixEnvelope.ramps) if (!ramp.rising && ramp.activeSamples < 0)
                    span.soundingEnd = std::min(span.soundingEnd,piece.mixEnvelope.startSeconds
                        +(ramp.start+ramp.length)/piece.mixEnvelope.sampleRate);
            }
            spans.push_back(std::move(span));
        }
    for (const auto& hit : noteHits)
    {
        if (!selectedNotes.contains(hit.id.toStdString()) || usesCvvcEnvelope(hit.id)) continue;
        const auto* note = findNote(hit.id); const auto* track = trackForNote(hit.id);
        if (!note || !track) continue;
        const auto start = hit.startSeconds + hit.clipStartSeconds;
        auto from = start, to = start + note->durationSeconds;
        if (trackUsesVoicebankSynthesis(*track))
        {
            // Pending OTO/phoneme data is not evidence of an overlap.
            const auto sound = utauSoundSpans.find(hit.id.toStdString());
            if (sound == utauSoundSpans.end() || (track->chineseCvvc && track->utauMode==UtauMode::classic
                && !trackIsDiffSinger(*track))) return 0;
            from = sound->second.first; to = sound->second.second;
        }
        auto points = unscaledAmplitudeEnvelope(amplitudeEnvelopeFor(*note,start),note->amplitudeEnvelopeBasePercent);
        for (auto& p : points) p.timeSeconds += start;
        spans.push_back({hit.id,0,from,to,std::move(points)});
    }
    const auto count = model.crossfadeNotes(std::move(spans),revision,curved);
    if (count > 0) { setTool(Tool::amplitude); refreshFromModel(); repaint(); }
    return count;
}

std::vector<juce::Point<float>> PianoRollComponent::diagnosticCvvcEnvelopeHandles(
    const juce::String& id,int part,bool amplitude) const
{
    std::vector<juce::Point<float>> result;
    const auto* note=findNote(id);if(!note)return result;
    for(const auto& piece:cvvcLanePieces(amplitude))if(piece.noteId==id&&piece.part==part)
        for(const auto& p:piece.points)result.push_back({timeToX(piece.from+p.position*(piece.to-piece.from)),
            amplitude?amplitudeLaneY(backend::envelopeDbFromGain(backend::envelopeGainFromDb(p.value)
                *note->amplitudeEnvelopeBasePercent/100.f)):flagLaneY(p.value)});
    return result;
}

bool PianoRollComponent::cvvcTimingEnabled(const juce::String& id) const
{
    const auto* track=trackForNote(id);
    return track && track->chineseCvvc && track->utauMode==UtauMode::classic
        && trackUsesVoicebankSynthesis(*track) && !trackIsDiffSinger(*track);
}

bool PianoRollComponent::usesCvvcEnvelope(const juce::String& id) const
{
    if (!cvvcTimingEnabled(id)) return false;
    const auto found=diffSingerPhonemes.find(id.toStdString());
    return found!=diffSingerPhonemes.end() && std::any_of(found->second.begin(),found->second.end(),
        [](const auto& p){return p.envelopePart>0;});
}

std::vector<PianoRollComponent::CvvcLanePiece> PianoRollComponent::cvvcLanePieces(bool amplitude) const
{
    std::vector<CvvcLanePiece> result;
    for (const auto& hit:noteHits)
    {
        if (!usesCvvcEnvelope(hit.id) || (!amplitude && !flagCurveActiveFor(hit.id))) continue;
        const auto* note=findNote(hit.id); if(!note)continue;
        const auto& spans=diffSingerPhonemes.at(hit.id.toStdString());
        const auto start=hit.startSeconds+hit.clipStartSeconds;
        double onset=0;
        for(const auto& span:spans)onset=std::min(onset,span.startSeconds-span.leadInSeconds);
        std::vector<backend::UtauAmplitudePoint> parent;
        if(amplitude)
        {
            for(const auto& p:note->amplitudeEnvelope)parent.push_back({p.timeSeconds,p.gainDb,p.linearToNext});
            parent=backend::UtauRenderer::fitAmplitudeEnvelope(parent,-onset,note->durationSeconds);
        }
        const auto flags=amplitude?std::vector<FlagCurvePoint>{}:flagLaneCurveFor(*note);
        for(const auto& span:spans)
        {
            if(span.envelopePart<=0)continue;
            CvvcLanePiece piece {hit.id,span.token,amplitude?juce::String():laneFlag,span.envelopePart,
                start+span.startSeconds-span.leadInSeconds,start+span.endSeconds,{}};
            piece.mixEnvelope=span.mixEnvelope;
            piece.mixEnvelope.startSeconds+=start;
            if(piece.to-piece.from<1.e-6)continue;
            if(const auto part=note->cvvcEnvelopes.find(piece.part);part!=note->cvvcEnvelopes.end())
            {
                auto curve=part->second.find(piece.key);
                if(curve==part->second.end() && piece.key.startsWith("HIFI:")
                    && std::none_of(note->utauFlagCurves.begin(),note->utauFlagCurves.end(),[&](const auto& c){return c.flag==piece.key;}))
                    curve=part->second.find(piece.key.substring(5));
                if(curve!=part->second.end())
                {
                    piece.points=curve->second;
                    if(piece.points.empty()&&!amplitude)
                        piece.points={{0,flagCurveKindFor(piece.key).defaultValue,true},{1,flagCurveKindFor(piece.key).defaultValue,true}};
                }
            }
            if(piece.points.empty() && amplitude && note->amplitudeEnvelope.empty())
                piece.points=backend::standardCvvcEnvelope(piece.to-piece.from);
            if(piece.points.empty())
            {
                // Slice the inherited curve at the actual sounding boundaries.
                const auto from=piece.from-start,to=piece.to-start;
                std::vector<double> times {from,to};
                backend::CvvcEnvelopeCurve source;
                if(amplitude)for(const auto& p:parent)
                {source.push_back({p.timeSeconds,p.gainDb,p.linearToNext});if(p.timeSeconds>from&&p.timeSeconds<to)times.push_back(p.timeSeconds);}
                else for(const auto& p:flags)if(p.timeSeconds>from&&p.timeSeconds<to)times.push_back(p.timeSeconds);
                std::sort(times.begin(),times.end());
                for(const auto t:times)
                {
                    auto linear=true;
                    if(amplitude)for(const auto& p:source)if(p.position<=t)linear=p.linear;
                    piece.points.push_back({(t-from)/(to-from),amplitude
                        ?backend::cvvcEnvelopeValue(source,t,true):flagCurveValueAt(flags,t),linear});
                }
            }
            if(cvvcLaneDrag && cvvcLaneDrag->piece.noteId==piece.noteId
                && cvvcLaneDrag->piece.part==piece.part && cvvcLaneDrag->piece.key==piece.key)
                piece.points=cvvcLaneDrag->piece.points;
            if(pointGroupGesture)for(const auto& d:pointGroupGesture->curves)
                if(d.identity.kind==PointSelection::cvvc&&d.identity.noteId==piece.noteId&&d.identity.part==piece.part&&d.identity.key==piece.key)
                    piece.points=d.edit.cvvcPoints;
            result.push_back(std::move(piece));
        }
    }
    return result;
}

int PianoRollComponent::drawCvvcEnvelopeLane(juce::Graphics& g,bool amplitude) const
{
    auto pieces=cvvcLanePieces(amplitude);
    const auto focused=hasSelectedCvvcPhoneme();
    // The selected phoneme is painted last where lead-ins overlap.
    std::stable_sort(pieces.begin(),pieces.end(),[&](const auto& a,const auto& b){
        return (a.noteId==cvvcSelectedNote&&a.part==cvvcSelectedPart)
             < (b.noteId==cvvcSelectedNote&&b.part==cvvcSelectedPart);});
    const auto plot=amplitude?amplitudeLanePlotBounds():flagLanePlotBounds();
    juce::Graphics::ScopedSaveState save(g);g.reduceClipRegion(plot.toNearestInt().expanded(7));
    for(const auto& piece:pieces)
    {
        const auto left=timeToX(piece.from),right=timeToX(piece.to);
        const auto hasMix=amplitude&&piece.mixEnvelope.available();
        auto soundEnd=hasMix?piece.mixEnvelope.endSeconds():piece.to;
        if(hasMix)for(const auto& ramp:piece.mixEnvelope.ramps)
            if(!ramp.rising&&ramp.activeSamples<0)
                soundEnd=std::min(soundEnd,piece.mixEnvelope.startSeconds+(ramp.start+ramp.length)/piece.mixEnvelope.sampleRate);
        if(std::max(right,timeToX(soundEnd))<plot.getX()||left>plot.getRight())continue;
        const auto selected=focused&&piece.noteId==cvvcSelectedNote&&piece.part==cvvcSelectedPart;
        const auto editable=!focused||selected||!selectedPoints.empty();
        const auto laneBase=Palette::graphBackground.overlaidWith(Palette::panel.withAlpha(.97f));
        const auto colour=rollInk(rollRole(
            juce::Colour(amplitude?(piece.part==1?0xff70d9d0:piece.part==3?0xffc1a0f4:0xffffb65e):0xff80c6ef),
            amplitude?(piece.part==1?Palette::noteEdge:piece.part==3?Palette::text:Palette::textMuted):Palette::heading)
            .withAlpha(selected?1.f:focused?.35f:.80f),laneBase);
        const auto laneSurface=laneBase.overlaidWith(colour.withAlpha(selected?.10f:.025f));
        const auto* note=findNote(piece.noteId);
        const auto yFor=[&](float value){return amplitude?amplitudeLaneY(backend::envelopeDbFromGain(
            backend::envelopeGainFromDb(value)*(note?note->amplitudeEnvelopeBasePercent:100.f)/100.f)):flagLaneY(value);};
        const juce::Rectangle<float> area(left,plot.getY(),right-left,plot.getHeight());
        g.setColour(colour.withAlpha(selected?.10f:.025f));g.fillRect(area);
        g.setColour(colour.withAlpha(.25f));g.drawVerticalLine(static_cast<int>(left),plot.getY(),plot.getBottom());
        g.drawVerticalLine(static_cast<int>(right),plot.getY(),plot.getBottom());
        const auto labelY=plot.getY()+static_cast<float>((piece.part==1?1:piece.part==3?2:0)*15);
        g.setColour(rollText(colour,laneSurface));g.setFont(11.f);
        if(phonemeInformationVisible(piece.noteId))
            g.drawText(piece.token,static_cast<int>(std::max(left+3,plot.getX())),static_cast<int>(labelY),
                std::max(16,static_cast<int>(right-std::max(left+3,plot.getX()))),14,juce::Justification::centredLeft,true);
        juce::Path path;
        const auto steps=juce::jlimit(2,1600,static_cast<int>(right-left));
        for(int i=0;i<=steps;++i)
        {
            const auto t=static_cast<double>(i)/steps;
            const auto p=juce::Point<float>(left+static_cast<float>(t)*(right-left),yFor(backend::cvvcEnvelopeValue(piece.points,t,amplitude)));
            if(i==0)path.startNewSubPath(p);else path.lineTo(p);
        }
        if(hasMix)
        {
            // Keep the user's handles on the unmultiplied curve. The solid
            // result is read-only, so automatic fades are never baked back
            // into the project or applied twice while editing.
            juce::Path dashed;const float lengths[]{4.f,4.f};
            juce::PathStrokeType(1.f).createDashedStroke(dashed,path,lengths,2);
            if(editable){g.setColour(rollInk(colour.withMultipliedAlpha(.42f),laneSurface));g.fillPath(dashed);}
            for(const auto& ramp:piece.mixEnvelope.ramps)if(ramp.crossfade)
            {
                const auto from=piece.mixEnvelope.startSeconds+ramp.start/piece.mixEnvelope.sampleRate;
                const auto to=std::min(soundEnd,from+std::min(ramp.length,ramp.activeSamples<0?ramp.length:ramp.activeSamples)/piece.mixEnvelope.sampleRate);
                const auto x1=std::max(plot.getX(),timeToX(from)),x2=std::min(plot.getRight(),timeToX(to));
                if(x2>x1)
                {
                    g.setColour(colour.withAlpha(.09f));g.fillRect(x1,plot.getY()+45.f,x2-x1,plot.getHeight()-45.f);
                    if(x2-x1>32.f){g.setColour(rollText(colour.withAlpha(.7f),laneSurface.overlaidWith(colour.withAlpha(.09f))));g.setFont(10.f);
                        g.drawText(I18n::uiText("交叉"),static_cast<int>(x1),static_cast<int>(plot.getY()+45),static_cast<int>(x2-x1),14,juce::Justification::centred);}
                }
            }
            const auto x1=std::max(plot.getX(),timeToX(piece.mixEnvelope.startSeconds));
            const auto x2=std::min(plot.getRight(),timeToX(soundEnd));
            if(x2>x1)
            {
                juce::Path effective;
                const auto count=std::max(2,static_cast<int>(std::ceil(x2-x1)));
                for(int i=0;i<=count;++i)
                {
                    const auto x=x1+(x2-x1)*static_cast<float>(i)/count;
                    const auto time=piece.mixEnvelope.startSeconds+(x-timeToX(piece.mixEnvelope.startSeconds))/pixelsPerSecond;
                    const auto raw=piece.mixEnvelope.replacesStandardEnvelope
                        &&backend::isStandardCvvcEnvelope(piece.points,piece.to-piece.from)?0.f
                        :backend::cvvcEnvelopeValue(piece.points,(time-piece.from)/(piece.to-piece.from),true);
                    const auto y=yFor(backend::envelopeDbFromGain(backend::envelopeGainFromDb(raw)*piece.mixEnvelope.gainAt(time)));
                    if(i==0)effective.startNewSubPath(x,y);else effective.lineTo(x,y);
                }
                auto fill=effective;fill.lineTo(x2,plot.getBottom());fill.lineTo(x1,plot.getBottom());fill.closeSubPath();
                g.setColour(colour.withAlpha(selected?.08f:.035f));g.fillPath(fill);
                g.setColour(colour);g.strokePath(effective,juce::PathStrokeType(selected?2.5f:1.8f));
            }
        }
        else {g.setColour(colour);g.strokePath(path,juce::PathStrokeType(selected?2.2f:1.4f));}
        if(editable)for(size_t index=0;index<piece.points.size();++index)
        {
            const auto& p=piece.points[index];
            const auto active=pointIsSelected(PointSelection::cvvc,piece.noteId,static_cast<int>(index),piece.part,piece.key);
            const juce::Point<float> centre(left+static_cast<float>(p.position)*(right-left),yFor(p.value));
            g.setColour(active?colour:Palette::background);g.fillEllipse(centre.x-4,centre.y-4,8,8);
            g.setColour(colour);g.drawEllipse(centre.x-4,centre.y-4,8,8,selected?2.f:1.3f);
        }
    }
    return static_cast<int>(pieces.size());
}

bool PianoRollComponent::cvvcEnvelopeMouseDown(const juce::MouseEvent& event,bool addPoint)
{
    if(sourceEditMode || (tool!=Tool::amplitude&&tool!=Tool::flagCurve))return false;
    const auto amplitude=tool==Tool::amplitude;
    const auto plot=amplitude?amplitudeLanePlotBounds():flagLanePlotBounds();
    if(!plot.expanded(7).contains(event.position))return false;
    const auto pieces=cvvcLanePieces(amplitude);
    const auto focused=hasSelectedCvvcPhoneme();
    int chosen=-1,point=-1;float nearest=100000.f;
    for(size_t i=0;i<pieces.size();++i)
    {
        const auto& piece=pieces[i];
        const auto labelY=plot.getY()+static_cast<float>((piece.part==1?1:piece.part==3?2:0)*15);
        const auto onLabel=event.position.y>=labelY&&event.position.y<labelY+14;
        if(focused && !event.mods.isCtrlDown() && !groupPointHitTest && !onLabel && (piece.noteId!=cvvcSelectedNote||piece.part!=cvvcSelectedPart))continue;
        const auto left=timeToX(piece.from),right=timeToX(piece.to);
        if(event.position.x<left-7 || event.position.x>right+7)continue;
        const auto* note=findNote(piece.noteId);
        const auto yFor=[&](float value){return amplitude?amplitudeLaneY(backend::envelopeDbFromGain(
            backend::envelopeGainFromDb(value)*(note?note->amplitudeEnvelopeBasePercent:100.f)/100.f)):flagLaneY(value);};
        const auto position=juce::jlimit<double>(0.0,1.0,(event.position.x-left)/std::max(1.f,right-left));
        auto distance=std::abs(event.position.y-yFor(backend::cvvcEnvelopeValue(piece.points,position,amplitude)))+12.f;
        if(amplitude&&piece.mixEnvelope.available())
        {
            const auto time=piece.from+position*(piece.to-piece.from);
            const auto db=backend::envelopeDbFromGain(backend::envelopeGainFromDb(piece.mixEnvelope.replacesStandardEnvelope
                &&backend::isStandardCvvcEnvelope(piece.points,piece.to-piece.from)?0.f
                :backend::cvvcEnvelopeValue(piece.points,position,true))*piece.mixEnvelope.gainAt(time));
            distance=std::min(distance,std::abs(event.position.y-yFor(db))+12.f);
        }
        int handle=-1;
        for(size_t j=0;j<piece.points.size();++j)
        {
            const auto& p=piece.points[j];
            const auto d=event.position.getDistanceFrom({left+static_cast<float>(p.position)*(right-left),yFor(p.value)});
            if(d<=9.f && d<distance){distance=d;handle=static_cast<int>(j);}
        }
        // Names at the top can select overlapping phonemes without grabbing a point.
        if(onLabel){distance=-1;handle=-1;}
        if(distance<nearest){nearest=distance;chosen=static_cast<int>(i);point=handle;}
    }
    if(chosen<0)return focused; // Do not fall through to whole-note editing while a phoneme is focused.
    auto piece=pieces[static_cast<size_t>(chosen)];
    cvvcSelectedNote=piece.noteId;cvvcSelectedPart=piece.part;
    selectedNote=piece.noteId;selectedNotes={piece.noteId.toStdString()};
    if(onNoteSelected)onNoteSelected(piece.noteId);
    draggedNote.clear();dragMode=DragMode::none;
    if(event.mods.isPopupMenu())
    {
        deleteEnvelopePoint({piece.noteId,point,model.revisionNumber(),PointSelection::cvvc,piece.part,piece.key});
        repaint();return true;
    }
    bool changed=false;
    const auto continuous=!amplitude && flagMode==FlagEditMode::continuous;
    if((addPoint||continuous)&&point<0)
    {
        const auto position=juce::jlimit<double>(0.0,1.0,(event.position.x-timeToX(piece.from))/std::max(1.f,timeToX(piece.to)-timeToX(piece.from)));
        const auto at=std::lower_bound(piece.points.begin(),piece.points.end(),position,[](const auto& p,double t){return p.position<t;});
        point=static_cast<int>(at-piece.points.begin());
        if(at==piece.points.end()||std::abs(at->position-position)>1.e-5)
        {
            piece.points.insert(at,{position,backend::cvvcEnvelopeValue(piece.points,position,amplitude),true});
            changed=true;
        }
    }
    if(point>=0)
    {
        if(!continuous)selectedPoint=PointSelection{piece.noteId,point,model.revisionNumber(),PointSelection::cvvc,piece.part,piece.key};
        cvvcLaneDrag=CvvcLaneDrag{std::move(piece),point,model.revisionNumber(),changed,continuous};
    }
    if(continuous&&!addPoint)cvvcEnvelopeMouseDrag(event);
    if(addPoint)finishCvvcEnvelopeDrag();
    repaint();return true;
}

void PianoRollComponent::cvvcEnvelopeMouseDrag(const juce::MouseEvent& event)
{
    if(!cvvcLaneDrag)return;
    auto& drag=*cvvcLaneDrag;
    auto position=juce::jlimit<double>(0.0,1.0,(event.position.x-timeToX(drag.piece.from))/std::max(1.f,timeToX(drag.piece.to)-timeToX(drag.piece.from)));
    if(drag.continuous)
    {
        auto& points=drag.piece.points;
        const auto previous=points[static_cast<size_t>(drag.point)].position;
        const auto from=std::min(previous,position),to=std::max(previous,position);
        std::erase_if(points,[&](const auto& p){return p.position>0&&p.position<1&&p.position>=from&&p.position<=to;});
        auto at=std::lower_bound(points.begin(),points.end(),position,[](const auto& p,double t){return p.position<t;});
        const auto value=flagValueFromLaneY(event.position.y);
        if(at!=points.end()&&std::abs(at->position-position)<1.e-6)at->value=value;
        else at=points.insert(at,{position,value,true});
        drag.point=static_cast<int>(at-points.begin());
        // Preserve the two ends and the current cursor while respecting the engine's point budget.
        while(points.size()>60)
        {
            size_t erase=1;double error=1.e30;
            for(size_t i=1;i+1<points.size();++i)if(static_cast<int>(i)!=drag.point)
            {
                const auto u=(points[i].position-points[i-1].position)/(points[i+1].position-points[i-1].position);
                const auto cost=std::abs(points[i].value-(points[i-1].value+(points[i+1].value-points[i-1].value)*u));
                if(cost<error){error=cost;erase=i;}
            }
            points.erase(points.begin()+static_cast<std::ptrdiff_t>(erase));
            if(static_cast<int>(erase)<drag.point)--drag.point;
        }
        drag.changed=true;repaint();return;
    }
    auto& p=drag.piece.points[static_cast<size_t>(drag.point)];
    // End handles identify the sounding range; the inner points are freely timed.
    if(drag.point>0&&drag.point+1<static_cast<int>(drag.piece.points.size()))
        p.position=juce::jlimit(drag.piece.points[static_cast<size_t>(drag.point-1)].position+1.e-6,
            drag.piece.points[static_cast<size_t>(drag.point+1)].position-1.e-6,position);
    auto value=drag.piece.key.isEmpty()?amplitudeDbFromLaneY(event.position.y):flagValueFromLaneY(event.position.y);
    if(drag.piece.key.isEmpty())if(const auto* note=findNote(drag.piece.noteId))
        value=backend::envelopeDbFromGain(backend::envelopeGainFromDb(value)/std::max(.001f,note->amplitudeEnvelopeBasePercent/100.f));
    if(event.mods.isShiftDown())value=p.value+(value-p.value)*.1f;
    p.value=value;drag.changed=true;repaint();
}

void PianoRollComponent::finishCvvcEnvelopeDrag()
{
    if(!cvvcLaneDrag)return;
    auto drag=std::move(*cvvcLaneDrag);cvvcLaneDrag.reset();
    if(drag.changed)
    {
        const auto committed=model.setCvvcEnvelope(drag.piece.noteId,drag.piece.part,drag.piece.key,
            std::move(drag.piece.points),drag.revision);
        if(committed && selectedPoint && !drag.continuous)selectedPoint->revision=model.revisionNumber();
    }
    repaint();
}
